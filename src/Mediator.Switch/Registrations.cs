using System.ComponentModel;
using System.Runtime.CompilerServices;

namespace Mediator.Switch;

/// <summary>
/// Receives a generated mediator's components, one call each: the service it is resolved as, its implementation
/// type and, where the generated code can call its constructor, a factory that does, so no container needs
/// reflection to create it. A container extension implements this to add the components to its container.
/// </summary>
public interface ISwitchMediatorRegistrar
{
    /// <param name="serviceType">The type the component is resolved as.</param>
    /// <param name="implementationType">The component's own type.</param>
    /// <param name="factory">Creates the component; null where its constructor is not accessible to the generated code.</param>
    /// <param name="notificationType">For a notification handler, the notification it handles; null otherwise.
    /// A notification's handlers arrive one after another.</param>
    void Add(Type serviceType, Type implementationType, Func<IServiceProvider, object>? factory, Type? notificationType);
}

/// <summary>
/// Where generated mediators leave their registrations for container extensions, which cannot name the generated
/// members of the mediator type they are given. A mediator adds its registrations from its static constructor.
/// </summary>
[EditorBrowsable(EditorBrowsableState.Never)]
public static class SwitchMediatorRegistrations
{
    private static readonly Dictionary<Type, Action<ISwitchMediatorRegistrar>> Sources = new();

    /// <summary>Called by generated code.</summary>
    [EditorBrowsable(EditorBrowsableState.Never)]
    public static void Add(Type mediatorType, Action<ISwitchMediatorRegistrar> register)
    {
        lock (Sources)
        {
            Sources[mediatorType] = register;
        }
    }

    /// <summary>
    /// Passes the components of <typeparamref name="TMediator"/> to <paramref name="registrar"/>; false when it was
    /// generated by a version that does not provide them (or declares its own static constructor).
    /// </summary>
    public static bool TryRegister<TMediator>(ISwitchMediatorRegistrar registrar) where TMediator : class
    {
        RuntimeHelpers.RunClassConstructor(typeof(TMediator).TypeHandle);
        Action<ISwitchMediatorRegistrar>? register;
        lock (Sources)
        {
            Sources.TryGetValue(typeof(TMediator), out register);
        }
        if (register == null)
        {
            return false;
        }
        register(registrar);
        return true;
    }
}
